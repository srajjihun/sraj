// .bat 파일이 한글을 화면에 찍을 때 쓰는 도우미입니다.
//
// 왜 필요한가:
//   cmd.exe 는 배치 파일을 조각조각 읽으면서 다음에 읽을 위치를 파일 안의
//   바이트 수로 기억합니다. chcp 65001(UTF-8) 상태에서 한글처럼 여러 바이트를
//   쓰는 글자가 그 조각의 경계에 걸리면 위치 계산이 어긋나, 다음 줄을 엉뚱한
//   글자 중간부터 읽습니다. 그러면 잘린 뒷조각을 명령으로 착각해
//     'ㅗ' is not recognized as an internal or external command
//   같은 오류가 납니다. 실제로 세 번 겪었습니다.
//
//   문구를 조금 고쳐 넘어가도 파일 크기가 달라지면 다른 줄에서 또 터집니다.
//   경계 위치가 바뀔 뿐 원인이 그대로이기 때문입니다. 그래서 근본 해결로
//   한글 안내문을 전부 이 파일로 옮기고, .bat 은 ASCII 만 남겼습니다.
//   Node 는 UTF-8 을 제대로 다루므로 이 문제가 없습니다.
//
// 규칙:
//   .bat 파일에는 한글을 쓰지 마세요. rem 주석도 마찬가지입니다
//   (cmd 는 주석 줄도 똑같이 읽고 위치를 셉니다).
//   사람에게 보여줄 한글은 전부 여기에 넣고 `node say.mjs <키>` 로 부릅니다.
//
// 사용법:
//   node scripts\g2b\say.mjs refresh-head
