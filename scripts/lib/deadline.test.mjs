let pass = 0;
const failures = [];

for (const [postDate, text, expected, label] of CASES) {
  const got = extractDeadline(postDate, text);
  if (got === expected) {
    pass += 1;
  } else {
    failures.push(`  ${label}\n     기대 ${expected} / 실제 ${got}\n     입력 ${JSON.stringify(text).slice(0, 90)}`);
  }
}

// 여러 텍스트를 넘기면 먼저 값이 나오는 것을 쓴다 (제목 -> 요약 순서 보장)
const order = extractDeadline("2026-08-01", "제목에는 없음", "신청 ~ 8. 20.");
if (order === "2026-08-20") pass += 1;
else failures.push(`  뒤 인자로 넘어가기\n     기대 2026-08-20 / 실제 ${order}`);

const total = CASES.length + 1;
console.log(`마감일 추출: ${pass}/${total} 통과`);
if (failures.length) {
  console.error("\n실패:\n" + failures.join("\n"));
  process.exit(1);
}
